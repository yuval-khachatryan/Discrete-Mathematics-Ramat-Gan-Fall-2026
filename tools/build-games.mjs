#!/usr/bin/env node
// node tools/build-games.mjs — bundle every game into ONE classic script.
//
// The games are written as ES modules (games/<name>/game.js importing
// ../shared/*.js), which is pleasant to edit and lets node test them. But
// browsers refuse to load module scripts from file:// pages, so a book opened
// by double-clicking an .html file showed empty games. Each index.html
// therefore loads games/<name>/game.bundle.js: the same code, bundled by
// esbuild into a plain IIFE that works from disk, from `quarto preview` and
// from GitHub Pages alike.
//
// Run after editing anything under games/ (quarto render runs it too, as a
// pre-render step). tests/bundles.test.mjs fails if a bundle is stale.
import { buildSync } from "esbuild";
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const GAMES = fileURLToPath(new URL("../games/", import.meta.url));
export const BANNER = "/* GENERATED by tools/build-games.mjs from game.js and ../shared/*.js. Do not edit: edit the sources and rebuild. */";

export function gameNames() {
  return readdirSync(GAMES, { withFileTypes: true })
    .filter(d => d.isDirectory() && existsSync(`${GAMES}${d.name}/game.js`))
    .map(d => d.name);
}

/** The bundle text for one game, without writing it. */
export function bundle(name) {
  return bundleFile(`${GAMES}${name}/game.js`);
}

/** Entry → output pairs: every game, plus the chapters' own interactive
    exercises (games/shared/book.js, loaded by _styles.html on every page). */
export function targets() {
  return [
    ...gameNames().map(name => ({ entry: `${GAMES}${name}/game.js`, out: `${GAMES}${name}/game.bundle.js`, label: `games/${name}/game.bundle.js` })),
    { entry: `${GAMES}shared/book.js`, out: `${GAMES}shared/book.bundle.js`, label: "games/shared/book.bundle.js" },
  ];
}

/** The bundle text for one entry file, without writing it. */
export function bundleFile(entry) {
  const r = buildSync({
    entryPoints: [entry], bundle: true, format: "iife", target: "es2019",
    charset: "utf8", legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent",
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const t of targets()) {
    writeFileSync(t.out, bundleFile(t.entry));
    console.log(t.label);
  }
}
