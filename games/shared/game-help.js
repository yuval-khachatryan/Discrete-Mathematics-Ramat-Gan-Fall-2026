export function gamePresentation(id,level){
 let goal=level.goal||'',help='';
 const take=(label)=>{
  const pattern=new RegExp(`<p><b>${label}:</b>[\\s\\S]*?</p>`,'g');
  goal=goal.replace(pattern,p=>{help+=p;return '';});
 };
 if(id==='circuit'&&circuitTasks[level.id]){
  take('המשימה');take('איך קוראים את התצוגה');
  goal+=`<p><b>המשימה:</b> ${circuitTasks[level.id]}</p>`;
  help=circuitHelp+help;
 }else if(id==='detective')take('איך משחקים');
 else if(id==='witness'){
  take('איך משחקים');
  if(help)goal='<p>התחום: ששת הסטודנטים המוצגים בכרטיסים.</p>'+goal;
 }else if(id==='barman'&&barmanTasks[level.id]){
  take('כללי השיחה');take('המשימה');
  goal+='<p>כל דמות יודעת רק מה היא רוצה ושומעת את התשובות שלפניה. עונים לפי הסדר ובכנות; כשאין מספיק מידע, עונים ״לא יודע/ת״.</p>';
  goal+=`<p><b>המשימה:</b> ${barmanTasks[level.id]}</p>`;
 }
 return {goal,help};
}
