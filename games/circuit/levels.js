/* levels.js — "תנו ירוק!".
   Every level is a formula drawn as a circuit. Each lever is a sentence, and
   the two-colour signal at the end of the wire shows the truth value of the
   whole formula: T = lever up / signal GREEN, F = lever down / signal RED.
   (The field is still called `lamp`: it holds the sentence the signal shows.)

   Fields
     id, title, goal, hints[3], debrief    (shell)
     mode      "play"     move the free levers until the signal shows the target colour
               "predict"  levers are set for you; say which colour the signal will show
               "explore"  try every lever setting; the truth table fills itself
               "fill"     the signal is hooded; fill in its column yourself
               "compare"  two circuits (formula, formula2); the robot claims they always
                          agree; refute with one differing row or confirm by checking all
     formula   logic.js syntax
     vars      {A: "sentence", ...}  — the order is the lever order
     lamp      the sentence the signal stands for
     start     initial lever values
     locked    {A: "why it cannot move"}        (play)
     target    true = make it green, false = make it red   (play; default true)
     impossible  true → show a "can't be done" button          (play)
     rounds    [{A:…, B:…}, ...]                (predict)
     formula2, claim, same   (compare) — same: the expected answer, checked by the tests
     view      "switch" | "lamp" | "dual" — the picture (circuit.js). Default: a single bulb for every formula.
               "dual" (green circuit φ + red circuit ¬φ) only from De Morgan on.
   tests/circuit.test.mjs checks that every play level is solvable exactly when
   it claims to be, and that every predict level has both colours. */

