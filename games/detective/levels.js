/* levels.js — "הבלש של הקפטריה". Pure data, no DOM.
   ---------------------------------------------------------------------------
   The book embeds single levels by id (?level=<id>&embed=1), so ids are stable.
   Besides the shell's {id, title, goal, hints, debrief}:
       mode      "derive" (build cards with the rules) | "judge" (the robot's arguments)
       atoms     {letter: {pos, neg}}: the two Hebrew sentences of every letter.
                 X, Y, Z are kept for the rule patterns; T, F are constants.
       suspect   sprite of the suspect in the scene (derive levels)
       guard / guardWin   the guard's opening and closing lines
       stamp     {text, kind}: a stamp on the suspect after the win (chain, culprit)
       winNote   an extra line after the win message
     derive:
       premises  the cards on the table, numbered 1, 2, … in this order
       target    the card to prove
       steps     the advertised length of a shortest proof
       solution  [[rule, n, m], …]: the proof that "פתרון" shows; derived cards
                 are numbered after the premises. tests/detective.test.mjs checks
                 that it is valid and as short as possible.
     judge:
       args      [{robot, premises, conclusion, answer, counter}] answer is
                 "mp" | "mt" | "hs" | "affirm" | "deny" (checked against classify)
                 counter = the story behind the counter-situation of a fallacy
       robotWin  the robot's closing line
   --------------------------------------------------------------------------- */

